import { expect, test } from '@playwright/test';

test('manages a policy through upload, preview, apply, rename and delete', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('textbox', { name: 'Your question' }).fill('Retain my question draft');
  await page.getByRole('link', { name: 'Manage policies', exact: true }).click();
  await expect(page).toHaveURL(/\/policies$/);
  await expect(page.getByRole('heading', { name: 'Manage policies' })).toBeVisible();
  await page.getByLabel('Policy file').setInputFiles({ name: 'travel-browser.txt', mimeType: 'text/plain', buffer: Buffer.from('Travel claims need original receipts. Managers approve travel costs.\n\n' .repeat(30)) });
  await page.getByRole('button', { name: 'Upload policy', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'travel browser', exact: true })).toBeVisible({ timeout: 20000 });
  await page.getByRole('button', { name: 'Chunking settings', exact: true }).click();
  await page.getByRole('combobox', { name: 'Strategy', exact: true }).selectOption('sentences');
  await page.getByLabel('Maximum chunk size (characters)').fill('200');
  await page.getByLabel('Overlap (characters)').fill('20');
  await expect(page.getByRole('button', { name: 'Apply changes' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Preview chunks', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Preview — not applied' })).toBeVisible();
  await page.getByLabel('Maximum chunk size (characters)').fill('220');
  await expect(page.getByRole('heading', { name: 'Preview — not applied' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Preview chunks', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Preview — not applied' })).toBeVisible();
  await page.getByRole('button', { name: 'Apply changes', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save title' })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Delete policy', exact: true })).toBeEnabled({ timeout: 20000 });
  await page.getByRole('button', { name: 'Chunking settings', exact: true }).click();
  await expect(page.getByText('Applied: sentences · 220 characters · 20 overlap.', { exact: false })).toBeVisible();
  await page.getByLabel('Display title').fill('Travel and expenses');
  await page.getByRole('button', { name: 'Save title', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Travel and expenses', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Chunks', exact: true }).click();
  await expect(page.getByText('Chunk 1', { exact: true })).toBeVisible();
  for (const [width, height] of [[1920, 1080], [1440, 900], [768, 1024], [390, 844], [320, 720], [844, 390]]) {
    await page.setViewportSize({ width, height });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await expect(page.getByLabel('Display title')).toBeVisible();
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: info.outputPath('library-desktop-light.png'), fullPage: true });
  await page.getByRole('button', { name: 'Switch to dark mode' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: info.outputPath('library-mobile-dark.png'), fullPage: true });
  await page.getByRole('link', { name: 'Ask policies', exact: true }).click();
  await expect(page.getByLabel('Your question')).toHaveValue('Retain my question draft');
  await page.goBack();
  await expect(page.getByRole('heading', { name: 'Manage policies' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Manage policies' })).toBeVisible();
  await page.getByRole('button', { name: /Travel and expenses.*travel-browser/ }).click();
  await page.getByRole('button', { name: 'Delete policy', exact: true }).click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Travel and expenses', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Delete policy', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
  await expect(page.getByRole('button', { name: /Travel and expenses.*travel-browser/ })).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('HTML strategy and safe content, invalid files and duplicates', async ({ page }) => {
  await page.goto('/policies');
  await page.getByLabel('Policy file').setInputFiles({ name: 'html-browser.html', mimeType: 'text/html', buffer: Buffer.from('<h1>Travel policy</h1><p>Keep all receipts.</p><script>window.injected = true</script><h2>Meals</h2><p>Ask your manager.</p>') });
  await page.getByRole('button', { name: 'Upload policy', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'html browser', exact: true })).toBeVisible({ timeout: 20000 });
  await expect(page.getByText('Keep all receipts.', { exact: false })).toBeVisible();
  expect(await page.evaluate(() => 'injected' in window)).toBe(false);
  await page.getByRole('button', { name: 'Chunking settings', exact: true }).click();
  await page.getByRole('combobox', { name: 'Strategy', exact: true }).selectOption('html');
  await expect(page.getByLabel('Split at heading levels up to')).toBeVisible();
  await page.getByRole('button', { name: 'Preview chunks', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Preview — not applied' })).toBeVisible();
  await page.getByLabel('Policy file').setInputFiles({ name: 'html-browser.html', mimeType: 'text/html', buffer: Buffer.from('<p>Duplicate.</p>') });
  await page.getByRole('button', { name: 'Upload policy', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('filename already exists');
  await page.getByLabel('Policy file').setInputFiles({ name: 'broken-browser.pdf', mimeType: 'application/pdf', buffer: Buffer.from('invalid pdf') });
  await page.getByRole('button', { name: 'Upload policy', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Retry processing' })).toBeVisible({ timeout: 20000 });
  await expect(page.getByRole('alert')).toContainText('PDF');
});
